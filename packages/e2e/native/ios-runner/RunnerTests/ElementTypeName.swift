import XCTest

/// `XCUIElement.ElementType` -> the capitalised name `RoleMap` keys on. A switch, not the raw value, so the compiler
/// checks the cases; anything the role map does not know reads as `Other`.
func elementTypeName(_ type: XCUIElement.ElementType) -> String {
  switch type {
  case .application: return "Application"
  case .window: return "Window"
  case .sheet: return "Sheet"
  case .drawer: return "Drawer"
  case .alert: return "Alert"
  case .dialog: return "Dialog"
  case .button: return "Button"
  case .radioButton: return "RadioButton"
  case .checkBox: return "CheckBox"
  case .disclosureTriangle: return "DisclosureTriangle"
  case .popUpButton: return "PopUpButton"
  case .comboBox: return "ComboBox"
  case .menuButton: return "MenuButton"
  case .toolbarButton: return "ToolbarButton"
  case .popover: return "Popover"
  case .keyboard: return "Keyboard"
  case .key: return "Key"
  case .navigationBar: return "NavigationBar"
  case .tabBar: return "TabBar"
  case .toolbar: return "Toolbar"
  case .table: return "Table"
  case .tableRow: return "TableRow"
  case .outline: return "Outline"
  case .browser: return "Browser"
  case .collectionView: return "CollectionView"
  case .slider: return "Slider"
  case .switch: return "Switch"
  case .toggle: return "Toggle"
  case .link: return "Link"
  case .image: return "Image"
  case .icon: return "Icon"
  case .searchField: return "SearchField"
  case .scrollView: return "ScrollView"
  case .staticText: return "StaticText"
  case .textField: return "TextField"
  case .secureTextField: return "SecureTextField"
  case .textView: return "TextView"
  case .menuItem: return "MenuItem"
  case .cell: return "Cell"
  case .tab: return "Tab"
  case .group: return "Group"
  case .webView: return "WebView"
  case .picker: return "Picker"
  case .pickerWheel: return "PickerWheel"
  case .pageIndicator: return "PageIndicator"
  case .progressIndicator: return "ProgressIndicator"
  case .activityIndicator: return "ActivityIndicator"
  case .segmentedControl: return "SegmentedControl"
  case .stepper: return "Stepper"
  case .datePicker: return "DatePicker"
  case .statusBar: return "StatusBar"
  case .map: return "Map"
  default: return "Other"
  }
}
